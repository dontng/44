def build_markdown(cfg):
    lines = []
    lines.append(f"# {cfg['title']}")
    lines.append("")
    lines.append("> 这组题直接分成两截：")
    for l in cfg['lead'][1:]:
        lines.append(f"> {l}")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(f"## 一、 {cfg['sec1_title']}")
    lines.append("")

    q_idx = 1
    for y, qnum, note in cfg['sec1_items']:
        tag = get_image_tag(y, qnum)
        lines.append(f"### {q_idx:02d} · {y}-{qnum}")
        lines.append(f"> *{note}*")
        lines.append(tag)
        lines.append("")
        q_idx += 1

    lines.append("---")
    lines.append("")
    lines.append(f"## 二、 {cfg['sec2_title']}")
    lines.append("")

    for y, qnum, note in cfg['sec2_items']:
        tag = get_image_tag(y, qnum)
        lines.append(f"### {q_idx:02d} · {y}-{qnum}")
        lines.append(f"> *{note}*")
        lines.append(tag)
        lines.append("")
        q_idx += 1

    if cfg['anchor_2026']:
        y, qnum = cfg['anchor_2026']
        lines.append(f"### {q_idx:02d} · {y}-{qnum}")
        lines.append("<!-- 2026 压轴题位，已在 paper_html/408-2026.html 就绪 -->")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"

def main():
    for cfg in SHEETS:
        out_path = ROOT / f"src/{cfg['filename']}"
        content = build_markdown(cfg)
        out_path.write_text(content, encoding="utf-8")
        total_q = len(cfg['sec1_items']) + len(cfg['sec2_items'])
        if cfg['anchor_2026']:
            total_q += 1
        print(f"Refactored {cfg['filename']}: {total_q} questions (Sec1: {len(cfg['sec1_items'])}, Sec2: {len(cfg['sec2_items'])}, 2026: {bool(cfg['anchor_2026'])})")

if __name__ == "__main__":
    main()
